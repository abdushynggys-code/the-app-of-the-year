-- Почта в заявке на ремонт.
-- Зачем: в ремонт чаще всего несут именно телефон. Позвонить на него нельзя —
-- он лежит у мастера. Почта даёт второй способ связи, который не ломается
-- вместе с устройством.
-- Применяется командой: npm run db:push

-- Поле необязательное: у части клиентов почты просто нет, и заставлять их
-- выдумывать адрес нельзя — иначе потеряем заявку целиком.
alter table public.repair_requests
  add column if not exists email text;

-- Простая проверка формата, пустое значение тоже допустимо.
-- Нужна, чтобы в поле не попадал мусор вроде «не знаю».
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'repair_requests_email_check'
  ) then
    alter table public.repair_requests
      add constraint repair_requests_email_check
      check (email is null or email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$');
  end if;
end $$;

-- Политики RLS менять не нужно: колонка живёт внутри уже защищённой таблицы,
-- и все существующие правила распространяются на неё автоматически.
-- Почту видит только владелец заявки и сотрудник из списка доступа.
--
-- Публичный поиск по коду (request_status_by_code) перечисляет колонки
-- поимённо и почту не возвращает — это важно и должно таким остаться:
-- иначе любой, кто подобрал чужой код, увидел бы личный адрес.
